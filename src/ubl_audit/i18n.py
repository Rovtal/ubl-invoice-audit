def validate_lang(lang: str) -> str:
    """Validate and normalize supported UI/report language codes ('tr' or 'en')."""
    normalized = lang.strip().lower()
    if normalized not in SUPPORTED_LANGS:
        raise ValueError(f"Unsupported language '{lang}'. Supported values: tr, en.")
    return normalized


def t(lang: str, key: str, **kwargs: Any) -> str:
    """Return a localized message string for the given language and key."""
    active = validate_lang(lang)
    template = MESSAGES[active][key]
    return template.format(**kwargs) if kwargs else template
